export type Msg = keyof typeof zh;

// The active language for code outside React (utils, api errors). Kept in
// sync by the provider.
let current: Lang = "en";

export function translate(msg: Msg, vars?: Vars, lang: Lang = current): string {
  const s: string = lang === "zh" ? zh[msg] || msg : msg;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
}

function detect(): Lang {
  try {
    const saved = window.localStorage.getItem(LANG_KEY);
    if (saved === "en" || saved === "zh") return saved;
  } catch {
    /* no storage: fall through to the browser language */
  }
  return navigator.language?.toLowerCase().startsWith("zh") ? "zh" : "en";
}

const Ctx = React.createContext<{ lang: Lang; setLang: (l: Lang) => void }>({ lang: "en", setLang: () => {} });

export function I18nProvider({ children }: { children: React.ReactNode }) {
  // The static export is prerendered in English; switch after mount so the
  // first client render matches the HTML.
  const [lang, setLangState] = React.useState<Lang>("en");
  React.useEffect(() => setLangState(detect()), []);
  current = lang;
  React.useEffect(() => {
    document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  }, [lang]);
  const setLang = React.useCallback((l: Lang) => {
    try {
      window.localStorage.setItem(LANG_KEY, l);
    } catch {
      /* the choice lasts for this page only */
    }
    setLangState(l);
  }, []);
  const value = React.useMemo(() => ({ lang, setLang }), [lang, setLang]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

/** `t(msg, vars)` in the active language, plus the language itself. */
export function useT() {
  const { lang, setLang } = React.useContext(Ctx);
  const t = React.useCallback((msg: Msg, vars?: Vars) => translate(msg, vars, lang), [lang]);
  return { t, lang, setLang };
}
